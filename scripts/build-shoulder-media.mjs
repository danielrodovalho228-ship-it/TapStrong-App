// Copies the checked clips and posters of the shoulder program into
// assets/media/shoulder and writes its manifest (Phase 32 B1, Daniel, Oct 4):
// the internal test build (EAS "apk" and "internal") carries them inside the
// app, so the shoulder sessions show our actor offline (airplane mode too).
// Only what passed the QC goes in (the same rule as assets/prototype/videos.js:
// no qc.json "suspect" clip, no "posterSuspect" image), and only exercises the
// program can use (never an overhead or behind-the-back one). Production
// builds never load it (bundle:check).
// Run: npm run shoulder:media
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FROM = join(ROOT, 'assets/prototype');
const TO = join(ROOT, 'assets/media/shoulder');

const manifest = readFileSync(join(FROM, 'videos.js'), 'utf8');
// Every slug of the program (its exercises and its warm-up), from the program itself.
const program = readFileSync(join(ROOT, 'src/features/rehab/programs.ts'), 'utf8');
const seed = new Map(
  JSON.parse(readFileSync(join(ROOT, 'supabase/seed/exercises.json'), 'utf8')).exercises.map(
    (e) => [e.slug, e],
  ),
);
// Shoulder above 90° or behind the back: never in the program (src/features/movement/overhead.ts).
const beyond = (slug) =>
  (seed.get(slug)?.joints ?? []).some(
    ([joint, move, range]) =>
      joint === 'shoulder' &&
      (move === 'overhead' ||
        move === 'reach_behind' ||
        ((move === 'flexion' || move === 'abduction') && range === 'full')),
  );
const slugs = [...new Set([...program.matchAll(/slug: '([a-z0-9_]+)'/g)].map((m) => m[1]))]
  .filter((s) => seed.has(s) && !beyond(s))
  .sort();

rmSync(TO, { recursive: true, force: true });
mkdirSync(join(TO, 'posters'), { recursive: true });
const lines = [];
const table = [];
for (const slug of slugs) {
  // The checked files of this exercise, as videos.js lists them.
  const row = manifest.split('\n').find((l) => l.startsWith(`  "${slug}": `)) ?? '';
  const files = [...row.matchAll(/require\("\.\/([^"]+)"\)/g)].map((m) => m[1]);
  const entry = {};
  for (const file of files) {
    const m = file.match(/^(posters\/)?[^.]+\.(f|m)\.(mp4|webp)$/);
    if (!m || !existsSync(join(FROM, file))) continue;
    copyFileSync(join(FROM, file), join(TO, file));
    const sex = m[2];
    if (m[1]) (entry.poster ??= {})[sex] = file;
    else entry[sex] = file;
  }
  table.push(
    `${slug}: clip ${['f', 'm'].filter((s) => entry[s]).join('/') || '-'}, poster ${
      ['f', 'm'].filter((s) => entry.poster?.[s]).join('/') || '-'
    }`,
  );
  if (!Object.keys(entry).length) continue;
  const req = (f) => `require("./${f}")`;
  const parts = ['f', 'm'].filter((s) => entry[s]).map((s) => `${s}: ${req(entry[s])}`);
  if (entry.poster)
    parts.push(
      `poster: { ${['f', 'm']
        .filter((s) => entry.poster[s])
        .map((s) => `${s}: ${req(entry.poster[s])}`)
        .join(', ')} }`,
    );
  lines.push(`  "${slug}": { ${parts.join(', ')} },`);
}
writeFileSync(
  join(TO, 'index.js'),
  `// GENERATED by scripts/build-shoulder-media.mjs. Do not edit.
// The shoulder program's checked clips and posters, inside the internal test build only.
module.exports = {
  // Marker checked by npm run bundle:check: in the internal build, never in production.
  __label: 'Bundled shoulder program media',
${lines.join('\n')}
};
`,
);
console.log(table.join('\n'));
console.log(`${lines.length} of ${slugs.length} shoulder exercises have bundled media.`);
