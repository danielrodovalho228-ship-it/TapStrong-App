// Writes assets/prototype/videos.js from the ex-*.mp4 files in that folder and
// map.json (file → exercise slug). Development builds only (SPEC §6).
// Run: npm run prototype:videos
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'prototype');
const map = JSON.parse(readFileSync(join(dir, 'map.json'), 'utf8'));
const seed = JSON.parse(
  readFileSync(join(dir, '..', '..', 'supabase', 'seed', 'exercises.json'), 'utf8'),
);
const slugs = new Set(seed.exercises.map((e) => e.slug));

const lines = [];
for (const file of readdirSync(dir)
  .filter((f) => /^ex-.*\.mp4$/.test(f))
  .sort()) {
  const slug = map[file];
  if (!slug) {
    console.warn(`skip ${file}: no exercise in map.json`);
    continue;
  }
  if (!slugs.has(slug)) throw new Error(`${file}: unknown exercise "${slug}"`);
  lines.push(`  ${JSON.stringify(slug)}: require(${JSON.stringify(`./${file}`)}),`);
}
for (const file of Object.keys(map)) {
  if (!existsSync(join(dir, file))) console.warn(`map.json lists ${file}, which is missing`);
}

writeFileSync(
  join(dir, 'videos.js'),
  [
    '// GENERATED by scripts/build-prototype-videos.mjs. Do not edit.',
    '// Prototype exercise videos: development builds only (SPEC §6).',
    'module.exports = {',
    '  // Marker checked by npm run bundle:check; must never reach a release bundle.',
    "  __label: 'Prototype exercise videos',",
    ...lines,
    '};',
    '',
  ].join('\n'),
);
console.log(`wrote ${lines.length} prototype videos to assets/prototype/videos.js`);
