// Writes assets/prototype/videos.js: one entry per exercise with its woman and
// man clips (Daniel, Phase 20: a man always sees the man, a woman the woman).
// Files: <slug>.f.mp4 and <slug>.m.mp4 in assets/prototype (made in Google
// Flow from body-adult-f-front / body-adult-m-front). Older ex-*.mp4 files
// are mapped in map.json as { "ex-name.mp4": { "slug": "push_up", "sex": "f" } }.
// Development builds only until the reviewer approves (SPEC §6).
// Run: npm run prototype:videos
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'prototype');
const map = JSON.parse(readFileSync(join(dir, 'map.json'), 'utf8'));
const root = join(dir, '..', '..');
const slugs = new Set(
  JSON.parse(readFileSync(join(root, 'supabase', 'seed', 'exercises.json'), 'utf8')).exercises.map(
    (e) => e.slug,
  ),
);
const repairFile = join(root, 'supabase', 'seed', 'repair_tests.json');
if (existsSync(repairFile))
  for (const t of JSON.parse(readFileSync(repairFile, 'utf8')).tests ?? [])
    slugs.add(t.slug ?? t.id);

/** slug → { f?: file, m?: file } */
const clips = {};
const put = (slug, sex, file) => {
  if (!slugs.has(slug)) throw new Error(`${file}: unknown exercise "${slug}"`);
  if (sex !== 'f' && sex !== 'm') throw new Error(`${file}: sex must be "f" or "m"`);
  clips[slug] = { ...clips[slug], [sex]: file };
};
for (const file of readdirSync(dir).sort()) {
  const named = file.match(/^(.+)\.(f|m)\.mp4$/);
  if (named) put(named[1], named[2], file);
  else if (/^ex-.*\.mp4$/.test(file)) {
    const entry = map[file];
    if (entry && typeof entry === 'object') put(entry.slug, entry.sex, file);
    // A clip with no sex is never shown: the other sex must never appear.
    else console.warn(`skip ${file}: map.json needs { "slug": …, "sex": "f" | "m" }`);
  }
}
for (const file of Object.keys(map))
  if (!existsSync(join(dir, file))) console.warn(`map.json lists ${file}, which is missing`);

const lines = Object.keys(clips)
  .sort()
  .map((slug) => {
    const sexes = ['f', 'm']
      .filter((s) => clips[slug][s])
      .map((s) => `${s}: require(${JSON.stringify(`./${clips[slug][s]}`)})`);
    return `  ${JSON.stringify(slug)}: { ${sexes.join(', ')} },`;
  });
writeFileSync(
  join(dir, 'videos.js'),
  [
    '// GENERATED by scripts/build-prototype-videos.mjs. Do not edit.',
    '// Exercise demo clips by sex (f / m): development builds only (SPEC §6).',
    'module.exports = {',
    '  // Marker checked by npm run bundle:check; must never reach a release bundle.',
    "  __label: 'Prototype exercise videos',",
    ...lines,
    '};',
    '',
  ].join('\n'),
);
const pairs = Object.values(clips).reduce((n, c) => n + Object.keys(c).length, 0);
console.log(`wrote ${pairs} clips for ${lines.length} exercises to assets/prototype/videos.js`);
